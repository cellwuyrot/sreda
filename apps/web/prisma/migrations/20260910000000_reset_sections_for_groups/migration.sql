-- SECTIONS-RESET: снимаем блочный режим с групп, которые его не выбирали.
--
-- ── Что произошло ───────────────────────────────────────────────────────────
--
-- POST /api/groups включал `sectionsEnabled` по пометке `section` у каналов
-- шаблона, а в каждом премиум-шаблоне такая пометка стояла. То есть любая
-- группа, созданная по шаблону («Игровое сообщество», «Проектная команда»,
-- «Поддержка», «Учебная группа»), получала блочный режим автоматически.
--
-- Дальше connect рисовал такую группу как ГЛАВНОЕ сообщество TZ Connect:
-- блочный интерфейс разделов вместо обычного списка каналов, а панель
-- «Разделы — рабочие модули группы» не появлялась вообще. Владелец при этом
-- ничего подобного не выбирал — он выбрал набор каналов, а получил чужой
-- интерфейс, и вернуть привычный вид было нечем: связь «шаблон → режим» в
-- настройках никак не объяснена.
--
-- ── Почему правим данные, а не только код ───────────────────────────────────
--
-- Схема не меняется: поле `sectionsEnabled` было и остаётся. Но код чинит
-- только БУДУЩИЕ группы, а уже созданные так и остались бы в режиме, который
-- им никто не назначал. Поэтому режим снимается со всех групп, кроме главного
-- сообщества: там блочный интерфейс — это и есть задуманный вид (isMain).
--
-- Данные при этом не теряются: каналы, посты и участники не трогаются, меняется
-- только способ показа. Если владелец хочет блочный вид осознанно — он
-- включается обратно одним переключателем «Разделы» в настройках группы
-- (доступен владельцу с premium). Ровно там этому выбору и место.
UPDATE "Group"
SET "sectionsEnabled" = false
WHERE "isMain" = false
  AND "sectionsEnabled" = true;
