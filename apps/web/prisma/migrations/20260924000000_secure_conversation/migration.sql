-- FIX-E2EECHAT: защищённая переписка — отдельный разговор (kind = 'SECURE').
--
-- Новых столбцов не нужно: kind уже строка. Нужна уникальность пары — ровно такая
-- же, как у личной переписки: одна пара — один защищённый чат. Без этого двое,
-- одновременно нажавшие «Защищённый чат», получили бы два разных чата и писали
-- каждый в свой, не видя собеседника. Prisma частичные индексы не описывает,
-- поэтому — чистый SQL, как и для PERSONAL.
CREATE UNIQUE INDEX IF NOT EXISTS "DirectConversation_secure_pair_key"
  ON "DirectConversation" ("user1Id", "user2Id")
  WHERE "kind" = 'SECURE';
