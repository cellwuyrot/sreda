-- VPN-ROUTING: выбор режима маршрутизации делает человек при включении VPN.
--
-- Раньше маршруты были одни на всех и задавались администратором: человек не мог
-- решить, гнать ли через туннель весь трафик или только сервисы TZ. Теперь
-- администратор задаёт СМЫСЛ двух вариантов, а выбор между ними хранится у пира.
--
-- Идемпотентно: миграция может доехать на базу, где её часть уже применена.

ALTER TABLE "VpnSettings" ADD COLUMN IF NOT EXISTS "serviceAllowedIps" TEXT NOT NULL DEFAULT '10.8.0.0/24';

-- Прежним пирам ставится ALL: именно так они и работают сейчас, если
-- администратор не менял маршруты. Молча переводить кого-то в другой режим
-- нельзя — на устройстве лежит уже выданный профиль, и он не изменится.
ALTER TABLE "VpnPeer" ADD COLUMN IF NOT EXISTS "routing" TEXT NOT NULL DEFAULT 'ALL';
