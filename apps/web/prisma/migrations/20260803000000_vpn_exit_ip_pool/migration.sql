-- VPN-EXIT: пул внешних адресов узла и закреплённый адрес выхода у пира.
--
-- Зачем: один узел = один внешний IP на всех его пользователей. Это и есть
-- настоящий потолок масштабирования — капчи, баны и странная геолокация
-- начинаются именно отсюда, а не из-за нехватки адресов в туннеле. Пул
-- внешних адресов снимает этот потолок без добавления машин.
--
-- Закрепление адреса за пиром принципиально: смена внешнего IP посреди работы
-- для банков и длинных сессий выглядит как смена пользователя и приводит к
-- разлогину. Поэтому адрес выдаётся один раз и держится.

ALTER TABLE "ServerNode" ADD COLUMN IF NOT EXISTS "publicIps" TEXT NOT NULL DEFAULT '';
ALTER TABLE "VpnPeer" ADD COLUMN IF NOT EXISTS "exitIp" TEXT NOT NULL DEFAULT '';
