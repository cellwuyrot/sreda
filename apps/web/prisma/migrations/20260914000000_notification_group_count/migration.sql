-- Группировка уведомлений одной беседы в одно.
--
-- Зачем: раньше каждое личное сообщение (или ответ по обращению) создавало
-- отдельную строку в журнале. Пять сообщений подряд из одного чата — пять
-- уведомлений и «5» в колокольчике вместо одного сгруппированного. Теперь
-- уведомление о том же предмете (беседе), пока оно не прочитано, обновляется на
-- месте, а `count` считает, сколько событий в нём схлопнуто.
--
-- Идемпотентно: миграция может доехать на базу, где её часть уже применена.

ALTER TABLE "Notification" ADD COLUMN IF NOT EXISTS "count" INTEGER NOT NULL DEFAULT 1;
