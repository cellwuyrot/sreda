-- VPN-WG: адрес пира уникален в пределах узла, а не всей системы.
--
-- Подсеть 10.8.0.0/24 поднимается на каждом VPN-узле, то есть 10.8.0.2 на двух
-- узлах — это два разных туннеля. Глобальная уникальность делала невозможным
-- второй узел: адрес выдаётся из подсети узла, и первый же пир на новом узле
-- упирался в чужую занятую запись.
--
-- Идемпотентно: миграция может доехать на базу, где её часть уже применена.

DROP INDEX IF EXISTS "VpnPeer_address_key";

CREATE UNIQUE INDEX IF NOT EXISTS "VpnPeer_nodeId_address_key" ON "VpnPeer"("nodeId", "address");
