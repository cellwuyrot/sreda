/**
 * Тесты: hooks/useMessageWindow — раскрытие хвоста ленты.
 *
 * Проверяется правило, которое чинит баг с кнопкой «вниз»: при большом
 * количестве сообщений нажатие не приводило в конец.
 *
 * Причина была не в анимации. При уходе вверх последние сообщения вынимаются
 * из дерева и заменяются нижней распоркой, высота которой — ОЦЕНКА (число
 * скрытых строк на среднюю высоту). Прокрутка приезжала в конец распорки; там
 * срабатывал обработчик, хвост отрисовывался по-настоящему, оценка сменялась
 * фактической высотой — и низ уезжал из-под ног.
 *
 * Отсюда инвариант, который здесь и закреплён: после раскрытия хвоста скрытых
 * снизу строк не остаётся ни одной. Пока это так, прокрутка в конец идёт по
 * настоящей высоте и попадает точно.
 */
import { describe, it, expect } from "vitest";
import { tailWindow } from "@/hooks/useMessageWindow";

/** Столько сообщений в ленте, чтобы окно точно включилось. */
const LONG = 5_000;

describe("FIX-SCROLLEND: раскрытие хвоста", () => {
  it("ИНВАРИАНТ: после раскрытия снизу не скрыто ни одной строки", () => {
    const next = tailWindow({ size: 100, hideBelow: 3_000 }, LONG);
    expect(next.hideBelow).toBe(0);
  });

  it("ФИКСАЦИЯ: размер окна не уменьшается — иначе лента дёрнется в момент наводки", () => {
    /* Убрать строки СВЕРХУ значит сдвинуть всё, что под ними. Делать это
       одновременно с прокруткой в конец — гарантированный промах. */
    const next = tailWindow({ size: 400, hideBelow: 1_200 }, LONG);
    expect(next.size).toBe(400);
  });

  it("хвост уже виден — состояние не меняется, лишней отрисовки нет", () => {
    const state = { size: 300, hideBelow: 0 };
    expect(tailWindow(state, LONG)).toBe(state);
  });

  it("короткая переписка: окно не включено, трогать нечего", () => {
    /* На полусотне сообщений в дереве и так вся лента — раскрывать нечего, и
       менять состояние значило бы вызвать отрисовку на ровном месте. */
    const state = { size: 100, hideBelow: 0 };
    expect(tailWindow(state, 50)).toBe(state);
  });

  it("окно меньше минимального подрастает до него", () => {
    const next = tailWindow({ size: 10, hideBelow: 500 }, LONG);
    expect(next.size).toBeGreaterThanOrEqual(100);
    expect(next.hideBelow).toBe(0);
  });

  it("повторный вызов ничего не меняет: раскрывать больше нечего", () => {
    const once = tailWindow({ size: 200, hideBelow: 2_000 }, LONG);
    expect(tailWindow(once, LONG)).toBe(once);
  });
});
