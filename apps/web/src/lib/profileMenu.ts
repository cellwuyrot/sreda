/**
 * MOBILE-PROFILE: что показать человеку в его собственном меню на телефоне.
 *
 * ── Зачем ───────────────────────────────────────────────────────────────────
 *
 * На телефоне верхняя панель скрыта, а в мессенджере её и не должно быть. Из-за
 * этого в приложении не было ни профиля, ни центра уведомлений, ни рабочей среды,
 * а у партнёра, редактора и администратора — их разделов: попасть туда было
 * НЕОТКУДА. Вместо этого рядом с «Присоединиться» стояла кнопка «Друзья»,
 * повторявшая раздел из нижней навигации.
 *
 * ── Почему списком, а не разметкой ──────────────────────────────────────────
 *
 * Состав меню зависит от роли, и это то самое место, где легко ошибиться: забыть
 * роль, показать чужой раздел, продублировать пункт. Список — данные, а данные
 * проверяются тестом; разметка вокруг них остаётся глупой.
 */

export interface ProfileMenuEntry {
  /** Куда ведёт. Все пути внутри своего приложения. */
  href: string;
  label: string;
  /** Пояснение под названием: одна строка, зачем это человеку. */
  hint: string;
  /** Роль, без которой пункта не видно. Пусто — виден всем. */
  role?: "CONSULTANT" | "EDITOR" | "ADMIN";
}

/**
 * Пункты в порядке показа: сначала то, что нужно каждому, потом разделы по роли.
 *
 * Порядок не косметика: собственные настройки и уведомления открывают чаще, чем
 * рабочие разделы, а роль есть у меньшинства — её пункты не должны отодвигать
 * общие.
 */
const ENTRIES: ProfileMenuEntry[] = [
  { href: "/settings", label: "Настройки профиля", hint: "Имя, аватар, приватность, оформление" },
  { href: "/settings/notifications", label: "Уведомления", hint: "Центр уведомлений и что о чём сообщать" },
  { href: "/workspace", label: "Рабочая среда", hint: "Личный холст: заметки, файлы, доски" },
  { href: "/partner", label: "Личный кабинет", hint: "Проекты и переписка по вашим заказам", role: "CONSULTANT" },
  { href: "/editor", label: "Редакторская", hint: "Правка содержимого сайта", role: "EDITOR" },
  { href: "/admin", label: "Панель администратора", hint: "Люди, сервисы, обращения, система", role: "ADMIN" },
];

/**
 * Меню для конкретной роли.
 *
 * ── Каждая роль видит ТОЛЬКО свой раздел ────────────────────────────────────
 *
 * Сначала здесь администратору показывалась и редакторская — с рассуждением, что
 * правка содержимого входит в его полномочия. Это была ошибка: меню перестало
 * совпадать с остальным продуктом, где «Редакторская» есть только у редактора, а
 * у администратора — своя панель. Разнобой в том, что человек видит, дороже любой
 * теоретической полноты прав: администратор ищет свою панель и не должен
 * разбираться, зачем ему второй похожий раздел.
 *
 * Правка содержимого сайта у администратора есть и без этого пункта — режимом
 * правки в верхней панели, а не отдельным разделом.
 */
export function profileMenuEntries(role?: string | null): ProfileMenuEntry[] {
  return ENTRIES.filter((entry) => !entry.role || entry.role === role);
}
