/**
 * Определение мобильной оболочки TZ.Connect (Android WebView) и её
 * навигационная политика.
 *
 * Android-клиент (apps/android) — это WebView, который существует только ради
 * раздела `/connect`. Оболочка добавляет к User-Agent маркер
 * `ConnectAndroid/<версия>` (см. MainActivity.configureWebView), по которому
 * веб-часть понимает, что работает внутри приложения, и:
 *   • скрывает ссылки, ведущие в «сайтовые» разделы (лендинг, /user/…,
 *     /library и т.д.) — атрибут data-shell-hide + CSS `.tz-android`;
 *   • глушит клики по ссылкам вне allowlist (AndroidShellGuard);
 *   • сама оболочка страхует всё это на нативном уровне
 *     (Config.isAllowedPath + doUpdateVisitedHistory в MainActivity).
 *
 * Списки путей здесь и в apps/android/.../Config.kt должны совпадать —
 * это ЕДИНСТВЕННЫЕ два места, где задаётся навигационная политика клиента.
 */

/**
 * Разделы, разрешённые внутри мобильной оболочки.
 *
 * ── Почему список расширен ──────────────────────────────────────────────────
 *
 * Сначала здесь был только сам мессенджер, и это оказалось слишком узко:
 * в приложении не было НИ профиля, НИ центра уведомлений, НИ рабочей среды, а у
 * партнёра — личного кабинета, у редактора и администратора — их разделов.
 * Колокольчик на телефоне существовал, но вёл в запрещённый путь: оболочка
 * возвращала человека в мессенджер, и уведомления выглядели как неработающие.
 *
 * Разделение простое: собственные разделы ЧЕЛОВЕКА (его настройки, его
 * уведомления, его рабочая среда, его кабинет по роли) — часть клиента и
 * попадают сюда. Сайтовые разделы (лендинг, каталог проектов, библиотека, игры,
 * чужие профили) остаются снаружи: ради них приложение не заводили.
 */
export const SHELL_ALLOWED_PREFIXES = [
  "/connect",   // сам мессенджер (включая /connect/services)
  "/auth",      // вход/регистрация — без них в мессенджер не попасть
  "/invite",    // приём приглашения в сообщество — часть флоу мессенджера
  "/uploads",   // загруженные файлы (вложения)
  "/api",       // redirect-цепочки NextAuth и загрузки
  "/settings",  // свой профиль и центр уведомлений (/settings/notifications)
  "/workspace", // своя рабочая среда
  "/partner",   // личный кабинет партнёра (роль CONSULTANT)
  "/editor",    // редакторская (роль EDITOR)
  "/admin",     // панель администратора (роль ADMIN)
] as const;

/** true, когда страница открыта внутри Android-оболочки Connect. */
export function isAndroidShell(): boolean {
  if (typeof navigator === "undefined") return false;
  return navigator.userAgent.includes("ConnectAndroid/");
}

/** Разрешён ли путь внутри оболочки (без учёта origin — он проверяется нативно). */
export function isAllowedShellPath(pathname: string): boolean {
  const clean = (pathname.split("?")[0] ?? "/").split("#")[0] ?? "/";
  return SHELL_ALLOWED_PREFIXES.some(
    (p) => clean === p || clean.startsWith(`${p}/`),
  );
}

/**
 * Куда отправлять человека после входа или регистрации.
 *
 * ── Зачем это отдельной функцией ────────────────────────────────────────────
 *
 * Страница входа брала адрес из `?callbackUrl`, а по умолчанию отправляла на
 * `/` — на лендинг сайта. Внутри оболочек (Android WebView, десктопное
 * приложение) лендинга не существует: они открыты ради `/connect`, и его же
 * ждёт человек, который только что зарегистрировался. Он попадал на главный
 * экран сайта и должен был искать вход в мессенджер сам.
 *
 * ── Заодно закрыта дыра с чужим адресом ─────────────────────────────────────
 *
 * `callbackUrl` приходит из строки запроса, то есть его задаёт кто угодно, кто
 * прислал ссылку. Значение подставлялось в переход без проверки — ссылка вида
 * `/auth/signin?callbackUrl=https://чужой-сайт` уводила человека на чужой сайт
 * СРАЗУ ПОСЛЕ успешного входа, где он ожидаемо ввёл бы пароль снова. Поэтому
 * принимаются только собственные пути: начинаются с одной косой черты и не
 * содержат схемы.
 */
export const AUTH_FALLBACK_PATH = "/";
export const SHELL_HOME_PATH = "/connect";

export function resolveAuthRedirect(raw: string | null | undefined, inShell: boolean): string {
  const fallback = inShell ? SHELL_HOME_PATH : AUTH_FALLBACK_PATH;
  const value = (raw ?? "").trim();

  /* Пустое значение, чужой адрес, протокол-относительный «//host» и любые схемы
     (в том числе javascript:) — отбрасываем и идём к себе. */
  if (!value || !value.startsWith("/") || value.startsWith("//")) return fallback;
  if (/^\/\\/.test(value)) return fallback;

  /* В оболочке путь ещё должен быть ей разрешён: лендинг и «сайтовые» разделы
     там не открываются вовсе, и переход на них выглядел бы как пустой экран. */
  if (inShell && !isAllowedShellPath(value)) return SHELL_HOME_PATH;
  /* А вот на страницу входа возвращать нельзя ни там, ни там: получилась бы
     петля «вошёл — снова вход». */
  if (isAuthPath(value)) return fallback;

  return value;
}

function isAuthPath(pathname: string): boolean {
  const clean = (pathname.split("?")[0] ?? "/").split("#")[0] ?? "/";
  return clean === "/auth" || clean.startsWith("/auth/");
}
