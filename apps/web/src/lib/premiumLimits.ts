/**
 * Пределы, которые снимает подписка. Числа живут здесь, а не в маршрутах.
 *
 * Длина сообщения считается отдельно (lib/messageLimits) — она нужна и клиенту
 * при вводе, и серверу при проверке, поэтому у неё свой модуль без зависимостей.
 * Здесь всё остальное: глубина истории, размер файла, очередь отложенных.
 *
 * Почему в одном месте: предел без подписки — это обещание, которое показывают
 * в разделе Premium и проверяют в трёх разных маршрутах. Стоит числу разойтись
 * хотя бы в одном, и витрина начнёт врать.
 */

/* Предел глубины истории отозван.

   Обычный аккаунт видел последние 30 дней, остальное пропадало из прокрутки и
   поиска. Со стороны человека это выглядело не как ограничение тарифа, а как
   потеря переписки: сообщения есть, но их не найти. Историю видят все, целиком.
   Функция historyCutoff и константа FREE_HISTORY_DAYS удалены — вместе с
   пунктом «Вся история переписки» из списка преимуществ. */

/** Размер одного файла, МБ. */
export const FREE_UPLOAD_MB = 10;
export const PREMIUM_UPLOAD_MB = 100;

/** Сколько отложенных сообщений можно держать в очереди без подписки. */
export const FREE_SCHEDULED_QUEUE = 2;

/**
 * Сколько своих эмодзи можно держать в одном сообществе.
 *
 * Предел считается по подписке ВЛАДЕЛЬЦА сообщества, а не того, кто загружает:
 * набор принадлежит месту, а не человеку. Иначе один премиум-модератор
 * «раздувал» бы набор, который потом остаётся без подписки.
 */
export const FREE_GROUP_EMOJI = 5;
export const PREMIUM_GROUP_EMOJI = 20;

/** Сторона картинки эмодзи. 128 — то же, что у Discord и Slack: на обычном
 *  экране эмодзи занимает 20–24 точки, поэтому 128 хватает и на тройной
 *  плотности, а весит такой WebP десяток килобайт. */
export const EMOJI_SIZE_PX = 128;

/** Сколько закреплённых сообщений помещается в канале и в переписке. */
export const FREE_PINS = 10;
export const PREMIUM_PINS = 50;

/** Предельный размер одного файла в байтах. */
export function uploadLimitBytes(premium: boolean): number {
  return (premium ? PREMIUM_UPLOAD_MB : FREE_UPLOAD_MB) * 1024 * 1024;
}

/** Предел закреплённых сообщений. */
export function pinLimit(premium: boolean): number {
  return premium ? PREMIUM_PINS : FREE_PINS;
}

/** Предел числа своих эмодзи в сообществе. */
export function groupEmojiLimit(ownerPremium: boolean): number {
  return ownerPremium ? PREMIUM_GROUP_EMOJI : FREE_GROUP_EMOJI;
}

/** Сколько отложенных сообщений разрешено держать; `null` — без ограничения. */
export function scheduledQueueLimit(premium: boolean): number | null {
  return premium ? null : FREE_SCHEDULED_QUEUE;
}
