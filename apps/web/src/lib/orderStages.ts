/** Набор по ключу. Нужен и коду, и тестам — искать по массиву каждый раз лишнее. */
const SET_BY_KEY = new Map(STAGE_SETS.map((set) => [set.key, set]));

/**
 * Ключ набора по названию услуги.
 *
 * Совпадение ищется подстрокой в нижнем регистре — так же, как у значков
 * разделов. Подстрока, а не начало слова: «Облачные» должно совпасть с «облач»,
 * а «Настройка систем» — с «систем», в каком бы падеже название ни стояло.
 *
 * Не совпало ничего — это новая услуга владельца, ей общий набор.
 */
export function stageSetKeyForService(serviceTitle: string | null | undefined): string {
  const name = (serviceTitle || "").toLowerCase();
  if (!name) return GENERIC_STAGE_KEY;
  for (const set of STAGE_SETS) {
    if (set.keywords.some((word) => name.includes(word))) return set.key;
  }
  return GENERIC_STAGE_KEY;
}

/** Этапы набора по его ключу. Неизвестный ключ — общий набор, а не пустота. */
export function stagesOfSet(key: string): OrderStage[] {
  const set = SET_BY_KEY.get(key) ?? SET_BY_KEY.get(GENERIC_STAGE_KEY)!;
  return set.titles.map((title, index) => ({ id: `${set.key}-${index + 1}`, title }));
}

/** Набор по умолчанию для услуги с таким названием. */
export function defaultStagesForService(serviceTitle: string | null | undefined): OrderStage[] {
  return stagesOfSet(stageSetKeyForService(serviceTitle));
}

/**
 * Привести к списку этапов то, что пришло из базы или из тела запроса.
 *
 * Возвращает null, если списка нет или в нём не осталось ни одного пригодного
 * этапа: это значит «своего набора нет, берём каталожный», и именно так
 * различаются «услугу не настраивали» и «настроили пустотой».
 *
 * Идентификаторы досоздаются здесь, а не в интерфейсе. Редактор шлёт новый шаг
 * без идентификатора — присвоить его на клиенте нельзя: два администратора,
 * добавившие шаг одновременно, получили бы один и тот же номер, и отметки
 * проектов слиплись бы.
 */
export function sanitizeStages(raw: unknown): OrderStage[] | null {
  if (!Array.isArray(raw)) return null;
  const items = raw.slice(0, MAX_STAGES);

  const explicitId = (item: unknown): string => {
    const record = item as { id?: unknown } | null;
    return typeof record?.id === "string" ? record.id.trim().slice(0, 40) : "";
  };

  /* Сначала занимаем ВСЕ указанные идентификаторы — в том числе те, что стоят
     ниже по списку. Без этого прохода новый этап, добавленный в начало, забрал
     бы себе «s1» у существующего, тот получил бы другой идентификатор, и все
     проекты услуги разом потеряли бы отметку по нему. */
  const reserved = new Set<string>();
  for (const item of items) {
    const id = explicitId(item);
    if (id) reserved.add(id);
  }

  const used = new Set<string>();
  const stages: OrderStage[] = [];
  let seq = 0;
  for (const item of items) {
    const record = item as { title?: unknown } | null;
    const rawTitle = typeof record?.title === "string" ? record.title : typeof item === "string" ? item : "";
    const title = rawTitle.replace(/\s+/g, " ").trim().slice(0, MAX_STAGE_TITLE);
    if (!title) continue;
    let id = explicitId(item);
    if (!id || used.has(id)) {
      /* Свободный номер ищем перебором: администратор мог удалить шаг «s2» и
         добавить новый — повторно выданный «s2» унаследовал бы отметки
         удалённого этапа у всех проектов. */
      do {
        seq += 1;
        id = `s${seq}`;
      } while (used.has(id) || reserved.has(id));
    }
    used.add(id);
    stages.push({ id, title });
  }
  return stages.length > 0 ? stages : null;
}

/** Услуга в том виде, в каком её знает этот модуль. */
export interface StagedService {
  title: string;
  /** Свой набор этапов услуги (JSON из базы) либо null/undefined — каталожный. */
  stages?: unknown;
}

/**
 * Этапы конкретной услуги: свой набор, если владелец его правил, иначе
 * каталожный. Услуги нет вовсе (проект заведён до появления связи) — набор
 * сайта: до этой правки других этапов в кабинете и не существовало, и подменять
 * их задним числом значило бы сдвинуть отметки уже идущих работ.
 */
export function stagesForService(service: StagedService | null | undefined): OrderStage[] {
  if (!service) return stagesOfSet("site");
  return sanitizeStages(service.stages) ?? defaultStagesForService(service.title);
}

/**
 * Отметки выполненных этапов, приведённые к текущему набору.
 *
 * Числа принимаются ради совместимости: до перехода на идентификаторы в
 * `stepsDone` лежали НОМЕРА пунктов. Миграция переводит их разом, но если она
 * почему-то не доехала на какой-то установке, кабинет должен показать прогресс,
 * а не обнулить его молча.
 *
 * Порядок результата — порядок набора, а не порядок отметок: список этапов
 * рисуется по набору, и одинаковый порядок избавляет от сортировки на каждой
 * отрисовке.
 */
export function normalizeDoneStages(raw: unknown, stages: OrderStage[]): string[] {
  if (!Array.isArray(raw)) return [];
  const known = new Set(stages.map((stage) => stage.id));
  const done = new Set<string>();
  for (const item of raw) {
    if (typeof item === "string" && known.has(item)) done.add(item);
    else if (Number.isInteger(item)) {
      const legacy = stages[item as number];
      if (legacy) done.add(legacy.id);
    }
  }
  return stages.filter((stage) => done.has(stage.id)).map((stage) => stage.id);
}

/**
 * Готовность в процентах.
 *
 * Считается от длины НАБОРА, а не от вшитого числа десять: у «Честного Знака»
 * восемь этапов, у сопровождения — шесть, и в каждом наборе последний
 * выполненный этап обязан давать ровно 100%, иначе кабинет показывает
 * законченную работу как незаконченную.
 */
export function stageProgress(done: readonly string[], stages: OrderStage[]): number {
  if (stages.length === 0) return 0;
  const known = new Set(stages.map((stage) => stage.id));
  const hits = new Set(done.filter((id) => known.has(id)));
  return Math.min(100, Math.round((hits.size / stages.length) * 100));
}

/**
 * Подпись под полоской прогресса.
 *
 * На ста процентах показываем название ПОСЛЕДНЕГО этапа набора, а не общее
 * «Проект запущен»: у обслуживания сайтов работа заканчивается словами «На
 * регулярном обслуживании», а у «Честного Знака» — «Работа в штатном режиме».
 * Запуск проекта там никто не обещал.
 */
export function stageStatusLabel(progress: number, status: string, stages: OrderStage[]): string {
  if (progress >= 100 || status === "LAUNCHED") {
    return stages[stages.length - 1]?.title ?? "Работы завершены";
  }
  if (progress === 0) return "Заявка на рассмотрении";
  return `Готово на ${progress}%`;
}
