/**
 * STAGES: этапы работы по УСЛУГЕ, а не один набор на всё подряд.
 *
 * ── Что было сломано ────────────────────────────────────────────────────────
 *
 * Личный кабинет показывал по каждому проекту один и тот же жёстко вшитый
 * список из десяти пунктов: «Дизайн-макет подготовлен», «Вёрстка выполнена»,
 * «Домен и хостинг настроены», «Проект запущен». Это этапы создания САЙТА.
 * Услуг же одиннадцать, и человеку, заказавшему подключение к «Честному Знаку»
 * или телеграм-бота, кабинет обещал вёрстку и хостинг, которых в его работе
 * нет и не будет. Прогресс при этом считался от тех же десяти пунктов, то есть
 * «проект готов на 40%» означало неизвестно что.
 *
 * ── Как устроено теперь ─────────────────────────────────────────────────────
 *
 * Набор этапов выбирается по услуге проекта. Услуги владелец заводит сам, а
 * значит набор нельзя привязывать к идентификатору строки в базе: сегодня это
 * `service-1`, завтра услугу пересоздали — и проект остался без этапов.
 * Поэтому набор ищется ПО НАЗВАНИЮ услуги, ровно тем же приёмом, что уже
 * работает у значков разделов (см. components/connect/BlockIcons.tsx):
 * упорядоченный список ключевых слов, первое совпадение выигрывает.
 *
 * Порядок в списке значим: узкое слово стоит раньше широкого. «Обслуживание
 * сайтов» и «Создание сайтов» обе содержат «сайт», и пока «обслуж» стоит выше,
 * обслуживание не получает этапы разработки с нуля.
 *
 * Услуга, не совпавшая ни с одним словом, — это НОВАЯ услуга, которую владелец
 * добавил сам. Ей достаётся общий набор из пяти шагов. Пустой список здесь
 * недопустим: кабинет показал бы карточку без этапов и без прогресса, а этапы
 * сайта — прямая ложь о содержании работ.
 *
 * ── Почему у этапа есть идентификатор ───────────────────────────────────────
 *
 * Выполненные этапы хранятся в проекте (`PartnerProject.stepsDone`). Раньше там
 * лежали НОМЕРА пунктов, и это работало ровно до тех пор, пока список был один
 * и неизменяемый. Теперь набор этапов правит владелец через шестерёнку у
 * услуги: удалил один шаг — и все номера ниже съехали, у проектов оказались
 * отмечены не те этапы. Поэтому хранится идентификатор этапа:
 *
 *   • переименование этапа отметку сохраняет (идентификатор тот же);
 *   • перестановка порядка отметку сохраняет;
 *   • удаление этапа убирает только его отметку и ничего не сдвигает.
 *
 * У этапов из каталога идентификаторы построены от ключа набора («site-1»,
 * «honest-3»): они одинаковы на любой установке, поэтому проект переживает и
 * пересоздание услуги, и перенос базы.
 *
 * Здесь только данные и чистые функции: ни React, ни обращений к базе.
 */

/**
 * Один этап работ: идентификатор для хранения отметки + видимое название.
 *
 * Псевдоним типа, а не интерфейс, намеренно: набор кладётся в JSON-поле Prisma,
 * а туда принимаются только типы с неявной индексной сигнатурой. У интерфейса
 * её нет, и запись потребовала бы приведения через `as unknown` в каждом месте.
 */
export type OrderStage = {
  id: string;
  title: string;
};

/** Предел длины названия этапа. Строка длиннее не читается в списке. */
