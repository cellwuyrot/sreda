/**
 * FIX-BLACK-EDIT: где разрешён инлайн-редактор текстов сайта.
 *
 * Инлайн-редактор задуман для витрины: администратор включает режим, кликает по
 * заголовку или абзацу посадочной страницы и правит текст на месте. Текст там
 * статичен и принадлежит проекту.
 *
 * Слушатели же вешались на `document` целиком и на всех страницах сразу. Внутри
 * мессенджера это ломало страницу до чёрного экрана: любое нажатие на текст чужого
 * сообщения гасилось через preventDefault/stopPropagation, элемент превращался в
 * contentEditable, в нём выделялось всё содержимое, а затем чужой код менял текстовые
 * узлы, которыми владеет React. На ближайшей же перерисовке ленты согласование
 * дерева падало, и срабатывала граница ошибок. К тому же отредактированный кусок
 * уезжал в тексты сайта и потом подставлялся всем подряд по позиции в вёрстке.
 *
 * Список сознательно запретительный, а не разрешительный: новая маркетинговая страница
 * должна получать редактирование сама собой, а вот забытый в списке раздел с живыми
 * данными — это снова чёрный экран.
 */
export const INLINE_EDIT_BLOCKED_PREFIXES = [
  "/connect",
  "/profile",
  "/settings",
  "/admin",
  "/partner",
  "/editor",
  "/workspace",
  "/auth",
  "/invite",
  "/user",
] as const;

/** Можно ли править тексты на этом пути. */
export function isInlineEditablePath(pathname: string | null | undefined): boolean {
  if (!pathname) return false;
  return !INLINE_EDIT_BLOCKED_PREFIXES.some(
    (prefix) => pathname === prefix || pathname.startsWith(prefix + "/"),
  );
}
