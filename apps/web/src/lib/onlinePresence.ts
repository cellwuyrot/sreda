import { ONLINE_WINDOW_MS } from "@/lib/timeAgo";

/**
 * Присутствие участников: слияние свежего списка «кто в сети» со списком, который
 * уже показан на экране.
 *
 * ── Зачем это нужно ─────────────────────────────────────────────────────────
 *
 * Список участников приходит вместе со снимком сообщества, и в нём у каждого
 * лежит `lastSeen` на момент открытия группы. Дальше снимок не перезапрашивается,
 * поэтому отметки присутствия замирают: человек, зашедший позже, так и остаётся
 * «был 3 дня назад», а тот, кто был в сети при открытии, через минуту гаснет
 * навсегда — его `lastSeen` просто стареет. Отсюда «пока не выйду из группы и не
 * зайду заново, ничего не меняется».
 *
 * ── Почему отдельный запрос, а не снимок группы ─────────────────────────────
 *
 * Раньше на открытом списке участников снимок группы перезапрашивался целиком —
 * вместе с каналами, разделами и модулями. Это дорого, и от этого отказались,
 * заодно потеряв обновление присутствия. Присутствие — данные частые и крошечные,
 * поэтому у них теперь свой запрос: он отдаёт ТОЛЬКО идентификаторы тех, кто в
 * сети. Размер ответа ограничен числом присутствующих, а не размером сообщества.
 *
 * Кого нет в ответе, того не трогаем: его `lastSeen` устареет сам и подпись
 * «был(а) N назад» продолжит расти. Так одинаково работают и «зашёл в сеть», и
 * «вышел из сети», причём второе — без единого лишнего байта.
 */

/** Отметка присутствия для слияния: у кого какое последнее посещение. */
export interface PresenceRow {
  user: { id: string; lastSeen?: string | null };
}

export interface OnlinePresence {
  /** Кто в сети прямо сейчас. */
  online: string[];
  /** Момент, которым сервер отвечал: он и становится их `lastSeen`. */
  at: string;
}

/**
 * Проставить свежее присутствие в уже показанный список.
 *
 * Возвращает НОВЫЙ массив, но элементы не пересобирает без нужды: строка, у
 * которой присутствие не изменилось, остаётся той же ссылкой — иначе список
 * перерисовывался бы целиком каждые полминуты.
 */
export function mergePresence<T extends PresenceRow>(rows: readonly T[], presence: OnlinePresence | null): T[] {
  if (!presence || presence.online.length === 0) return rows.slice();
  const online = new Set(presence.online);
  return rows.map((row) => {
    if (!online.has(row.user.id)) return row;
    if (row.user.lastSeen === presence.at) return row;
    return { ...row, user: { ...row.user, lastSeen: presence.at } };
  });
}

/**
 * Граница, с которой человек считается присутствующим. Серверу нужна та же, что
 * и клиенту, поэтому берётся из общего значения.
 */
export function presenceSince(now: number = Date.now()): Date {
  return new Date(now - ONLINE_WINDOW_MS);
}
