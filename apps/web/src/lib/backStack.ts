/**
 * BACK-STEP: «назад» как шаг назад, а не как переход в заранее известное место.
 *
 * ── Зацикливание: почему первая версия его допускала ────────────────────────
 *
 * Первая версия решала «есть ли куда возвращаться» по собственному следу, а сам
 * шаг делала историей браузера (`router.back()`). Это два РАЗНЫХ списка, и они
 * расходятся постоянно:
 *
 *   • смена раздела настроек меняет только запрос (`?cat=premium`) — в истории
 *     появляется запись, в следе нет: путь-то тот же;
 *   • мессенджер переписывает адрес на `/connect` через `replaceState`;
 *   • разделы `/connect` переключаются вообще без смены адреса.
 *
 * Дальше происходило вот что: след говорил «возвращаться есть куда», кнопка
 * звала историю, история отступала на запись с ТЕМ ЖЕ путём — и человек
 * оставался на месте. Нажимает ещё раз — снова на месте. Со стороны это ровно
 * то, о чём сообщили: «из настроек назад — снова настройки, и не выбраться».
 *
 * Поэтому шаг тоже делается по следу: снимаем свой шаг и переходим на путь,
 * который в следе перед ним. Один список — расходиться нечему.
 *
 * Чем платим: не восстанавливается позиция прокрутки (её умеет только настоящая
 * история). Это заметно меньшая беда, чем кнопка, из которой нельзя выйти.
 *
 * ── Что было ────────────────────────────────────────────────────────────────
 *
 * Кнопка «←» на страницах вела по фиксированному адресу: из настроек — в
 * мессенджер, из подраздела админки — в её корень. То есть она означала не «назад»,
 * а «в такое-то место». Пришёл в настройки уведомлений из панели администратора —
 * и «назад» уносит в мессенджер, хотя вернуться человек хотел туда, откуда пришёл.
 *
 * ── Почему нельзя просто позвать историю браузера ───────────────────────────
 *
 * Шаг назад по истории может увести НАРУЖУ приложения: на страницу, с которой
 * человек пришёл по ссылке, или вообще на предыдущий сайт в этой вкладке. Для
 * кнопки внутри приложения это неверно — она обещает вернуть в приложение.
 *
 * Поэтому здесь ведётся свой след посещений: пока в нём есть куда возвращаться,
 * «назад» делает шаг назад; когда след пуст (страницу открыли по прямой ссылке,
 * первой в этой вкладке), кнопка ведёт в место по умолчанию — то самое, куда она
 * вела раньше всегда.
 *
 * Модуль намеренно чистый: ни истории, ни хранилища, ни маршрутизатора. Это
 * решение о том, что считать шагом назад, — и оно проверяемо тестами.
 */

/** Сколько шагов помним. Больше не нужно: «назад» — это про недавнее. */
export const BACK_STACK_LIMIT = 20;

/**
 * Запомнить посещение пути.
 *
 * Отличить переход вперёд от возврата назад можно по самому следу: если новый
 * путь совпадает с предыдущим шагом, значит человек вернулся, и последний шаг
 * снимается. Иначе это переход вперёд.
 *
 * Повторное посещение того же пути шагом не считается: смена запроса в адресе
 * (`?section=dm`) не должна требовать двух нажатий «назад».
 */
export function recordVisit(stack: string[], path: string): string[] {
  if (!path) return stack;
  const last = stack[stack.length - 1];
  if (last === path) return stack;

  /* Вернулись на предыдущий шаг — снимаем последний, а не добавляем новый. */
  if (stack.length >= 2 && stack[stack.length - 2] === path) {
    return stack.slice(0, -1);
  }

  const next = [...stack, path];
  return next.length > BACK_STACK_LIMIT ? next.slice(next.length - BACK_STACK_LIMIT) : next;
}

/** Есть ли куда возвращаться внутри приложения. */
export function canStepBack(stack: string[]): boolean {
  return stack.length > 1;
}

export interface BackStepResult {
  /** Куда идти. null — в следе не осталось другого пути, нужен запасной. */
  target: string | null;
  /** След после шага. Верхним становится тот путь, куда мы переходим. */
  stack: string[];
}

/**
 * Шаг назад по следу.
 *
 * Главное правило: **вернуться на тот же путь нельзя**. Именно на этом кнопка и
 * зацикливалась — шаг «назад» приводил туда же, откуда его сделали, и повторное
 * нажатие ничего не меняло. Поэтому хвост следа, совпадающий с текущим путём,
 * снимается целиком, и только потом берётся предыдущий шаг.
 *
 * Текущий путь передаётся отдельно, а не берётся из вершины следа: след может
 * отстать (страницу открыли по прямой ссылке, трекер ещё не отработал), и
 * доверять его вершине как «где я сейчас» нельзя.
 *
 * Возвращается и новый след: после перехода вершиной должен стать путь, на
 * который мы перешли, иначе следующий шаг снова уведёт не туда.
 */
export function stepBack(stack: string[], currentPath: string): BackStepResult {
  /* Снимаем всё, что совпадает с текущим путём: и вершину, и повторы под ней. */
  let end = stack.length;
  while (end > 0 && stack[end - 1] === currentPath) end -= 1;

  if (end === 0) return { target: null, stack: currentPath ? [currentPath] : [] };

  const target = stack[end - 1]!;
  return { target, stack: stack.slice(0, end) };
}

/**
 * Куда ведёт «назад»: путь предыдущего шага либо null, если шага нет.
 *
 * Значение нужно не для перехода (переход делает история — так сохраняется
 * позиция прокрутки), а чтобы показать человеку, куда он вернётся, и чтобы это
 * можно было проверить тестом.
 */
export function previousPath(stack: string[]): string | null {
  return canStepBack(stack) ? stack[stack.length - 2]! : null;
}

/**
 * Свой ли это путь.
 *
 * Проверка не формальность: в хранилище вкладки может записать кто угодно —
 * расширение браузера, прежняя версия приложения, сам человек из консоли. Адрес
 * вида `//чужой-сайт` браузер понимает как чужой origin, поэтому одной проверки
 * «начинается со слэша» мало. Обратные слэши некоторые браузеры тоже приводят к
 * прямым — их отбрасываем по той же причине.
 */
export function isInAppPath(value: unknown): value is string {
  if (typeof value !== "string" || !value.startsWith("/")) return false;
  if (value.startsWith("//")) return false;
  return !value.includes("\\");
}

/** Разбор сохранённого следа. Мусор в хранилище — пустой след, а не падение. */
export function parseStack(raw: string | null): string[] {
  if (!raw) return [];
  try {
    const parsed = JSON.parse(raw);
    if (!Array.isArray(parsed)) return [];
    return parsed.filter(isInAppPath).slice(-BACK_STACK_LIMIT);
  } catch {
    return [];
  }
}
