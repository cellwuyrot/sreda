/**
 * FIX-SRVLINK: один признак «это канал услуги» на всё приложение.
 *
 * Каналы, рождённые из услуги (Админ ▸ Услуги), живут в блоках справа, а не
 * в списке текстовых чатов слева. Опознавать их только по serviceId нельзя:
 * на рабочей установке есть каналы с пустым serviceId — их завела старая сверка,
 * а потом услуга пересоздавалась. Именно они всплывали в «Текстовых чатах»
 * главного сообщества и выглядели «зашитыми»: первый из них становился
 * «общим чатом» сообщества.
 *
 * Окончания устойчивы: их ставит сверка (lib/mainCommunity), они же служат
 * признаком родства для осиротевших каналов.
 */
export const SERVICE_CHANNEL_SUFFIX = / \u2014 (\u041e\u0431\u0441\u0443\u0436\u0434\u0435\u043d\u0438\u0435|\u0412\u043e\u043f\u0440\u043e\u0441\u044b)$/;

export function isServiceLinkedChannel(ch: {
  name?: string | null;
  serviceId?: string | null;
}): boolean {
  if (ch.serviceId) return true;
  return !!ch.name && SERVICE_CHANNEL_SUFFIX.test(ch.name);
}
