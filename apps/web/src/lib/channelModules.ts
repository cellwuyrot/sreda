/**
 * MODULES: единый список рабочих модулей группы.
 *
 * ── Зачем этот файл ─────────────────────────────────────────────────────────
 *
 * «Модуль» — это канал не-переписочного типа: новости, вопросы-ответы, база
 * знаний, календарь, документы, задачи, рабочая среда, общественность. Панель
 * «Разделы — рабочие модули группы» (ModulesPanel) показывает их отдельной
 * колонкой, список каналов (ChannelSidebar) обязан их из себя ИСКЛЮЧИТЬ, а
 * «Рабочая среда» в настройках (WorkspaceManager) — уметь их добавлять.
 *
 * Раньше этот список был выписан в каждом из трёх мест руками, плюс четвёртой
 * копией лежал whitelist типов канала в POST /api/channels. Копии разъехались,
 * и разъезд был не теоретическим: APPEALS числился модулем в одной панели и не
 * числился в двух других, из-за чего канал обращений показывался дважды на
 * десктопе (в колонке модулей И в списке каналов) и один раз на мобильном; а
 * COMMUNITY, добавленный позже, забыли внести в whitelist смены типа канала —
 * PUT молча оставлял тип прежним.
 *
 * Отсюда правило: типы, подписи и названия по умолчанию живут ТОЛЬКО здесь.
 * Оформление (иконки и цвета) остаётся в компонентах — оно у панели модулей и
 * у настроек разное по размеру и стилю, и тащить JSX в lib незачем.
 *
 * ── Почему APPEALS не модуль ────────────────────────────────────────────────
 *
 * «Обращения» — канал платформенной поддержки, а не рабочий модуль группы:
 *   • разбирать обращения может только глобальный ADMIN/EDITOR (см. scope=admin
 *     в /api/appeals) — владельцу группы такой канал показывает лишь его
 *     собственные заявки;
 *   • POST /api/channels намеренно запрещает делать APPEALS пунктом списка
 *     раздела, а диалог создания канала предлагает только TEXT/VOICE;
 *   • канал обращений главного сообщества досоздаётся сам (ensureAppealsChannel).
 *
 * Поэтому APPEALS остаётся допустимым ТИПОМ канала (существующие каналы
 * работают, главное сообщество живёт), но модулем не считается и показывается
 * в общем списке каналов — в одном месте, а не в двух.
 */

/** Типы каналов, которые панель модулей показывает как «Разделы». */
export type ChannelModuleType =
  | "NEWS"
  | "QA"
  | "WIKI"
  | "CALENDAR"
  | "DOCS"
  | "TASKS"
  | "CANVAS"
  | "COMMUNITY";

export interface ChannelModule {
  type: ChannelModuleType;
  /** Подпись модуля: строка под названием канала в панели «Разделы». */
  label: string;
  /**
   * Имя канала при создании модуля.
   *
   * Совпадает с подписью намеренно: модуль, добавленный вручную из настроек, и
   * модуль, развёрнутый шаблоном сообщества, должны выглядеть одинаково —
   * иначе в одной группе «Новости», а в другой «важная-информация», и человек
   * ищет знакомый раздел глазами.
   */
  defaultName: string;
}

/** Порядок здесь — порядок карточек в настройках группы. */
export const CHANNEL_MODULES: ChannelModule[] = [
  { type: "NEWS", label: "Новости", defaultName: "Новости" },
  { type: "QA", label: "Вопросы-ответы", defaultName: "Вопросы-ответы" },
  { type: "WIKI", label: "База знаний", defaultName: "База знаний" },
  { type: "CALENDAR", label: "Календарь", defaultName: "Календарь" },
  { type: "DOCS", label: "Документы", defaultName: "Документы" },
  { type: "TASKS", label: "Задачи", defaultName: "Задачи" },
  { type: "CANVAS", label: "Рабочая среда", defaultName: "Рабочая среда" },
  { type: "COMMUNITY", label: "Общественность", defaultName: "Общественность" },
];

/** Только типы — для фильтров вида «это модуль или обычный канал». */
export const MODULE_TYPES: ChannelModuleType[] = CHANNEL_MODULES.map((m) => m.type);

/** Типы каналов переписки: они всегда в общем списке, а не в панели модулей. */
export const CHAT_CHANNEL_TYPES = ["TEXT", "VOICE"] as const;

/**
 * Полный whitelist типов канала для API.
 *
 * Кроме модулей и переписки сюда входят CATEGORY (папка в списке каналов) и
 * APPEALS (канал обращений, см. пояснение выше). Список закрытый: значение
 * приходит из тела запроса, и без проверки в базу легло бы что угодно, а
 * интерфейс потом рисовал бы такой канал «чем-то по умолчанию».
 */
export const CHANNEL_TYPES = [
  ...CHAT_CHANNEL_TYPES,
  ...MODULE_TYPES,
  "APPEALS",
  "CATEGORY",
] as const;

export type ChannelType = (typeof CHANNEL_TYPES)[number];

const MODULE_TYPE_SET = new Set<string>(MODULE_TYPES);
const CHANNEL_TYPE_SET = new Set<string>(CHANNEL_TYPES);

/** Показывать ли канал такого типа в панели «Разделы». */
export function isModuleType(type: unknown): type is ChannelModuleType {
  return typeof type === "string" && MODULE_TYPE_SET.has(type);
}

/** Допустим ли такой тип канала вообще (проверка входящих данных API). */
export function isChannelType(type: unknown): type is ChannelType {
  return typeof type === "string" && CHANNEL_TYPE_SET.has(type);
}

/** Описание модуля по типу — подпись и имя по умолчанию. */
export function moduleByType(type: unknown): ChannelModule | null {
  return CHANNEL_MODULES.find((m) => m.type === type) ?? null;
}
